export type HiMessageKey = keyof typeof hiMessages;

export function tHi(
  key: HiMessageKey,
  params?: Record<string, string | number>
): string {
  let text: string = hiMessages[key] ?? String(key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}
